"""A vanilla-Minecraft-like 5x7 bitmap font for measuring GUI text widths (tooling only; not shipped).

Advance widths match the vanilla ``ascii.png`` metrics (glyph width + 1 px spacing) so mock text
measures what ``font.width`` will measure in game. Accented Latin letters are drawn as the base
letter with a 1 px accent row (same 6 px advance as in vanilla). CJK code points are drawn as a
7x7 hatched placeholder with the vanilla Unifont advance of 9 px (8 + 1).
"""
from PIL import Image

_G = {}


def _d(ch, *rows):
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, ".") for r in rows]
    while len(rows) < 8:
        rows.append("." * w)
    _G[ch] = rows


