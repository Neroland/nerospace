_ACCENT = {"à": "a", "è": "e", "é": "e", "ì": "i", "ò": "o", "ù": "u", "À": "A", "È": "E", "É": "E", "Ì": "I", "Ò": "O", "Ù": "U"}


def _rows(ch):
    if ch in _G:
        return _G[ch]
    if ch in _ACCENT:
        base = list(_G[_ACCENT[ch]])
        w = len(base[0])
        acc = ("." * ((w - 1) // 2) + "#").ljust(w, ".")
        if ch == "i" or _ACCENT[ch] == "i":
            return ["#", ".", "#", "#", "#", "#", "#", "."]
        base[0] = acc
        return base
    if ord(ch) >= 0x2E80:  # CJK placeholder (Unifont 8 px + 1)
        return ["########", "#......#", "#.####.#", "#.#..#.#", "#.####.#", "#......#", "########", "........"]
    return _G["?"]


def width(text):
    return sum(len(_rows(c)[0]) + 1 for c in text)


def draw(img, x, y, text, colour, shadow=False):
    """Draws ``text`` with its top-left at (x, y) (the vanilla 9 px line: 7 px glyph + descender)."""
    px = img.load()
    if shadow:
        sh = (colour[0] // 4, colour[1] // 4, colour[2] // 4, colour[3])
        draw(img, x + 1, y + 1, text, sh, False)
    cx = x
    for ch in text:
        rows = _rows(ch)
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c == "#":
                    xx, yy = cx + rx, y + ry
                    if 0 <= xx < img.width and 0 <= yy < img.height:
                        px[xx, yy] = colour
        cx += len(rows[0]) + 1
    return cx - x


def draw_centered(img, cx, y, text, colour, shadow=False):
    return draw(img, cx - width(text) // 2, y, text, colour, shadow)


def ellipsize(text, max_w):
    if width(text) <= max_w:
        return text
    while text and width(text + "…") > max_w:
        text = text[:-1]
    return text.rstrip() + "…"


def wrap(text, max_w):
    lines, cur = [], ""
    for word in text.split(" "):
        cand = word if not cur else cur + " " + word
        if width(cand) <= max_w:
            cur = cand
        else:
            if cur:
                lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines
